pub fn generate() -> Result<Vec<u8>, String> {
    let result=crate::payload::build_payload(0xcbd,0xfa00,WORDS);
    if crate::manifest::sha256_hex(&result)!=SHA256 { return Err("direct SS payload hash mismatch".into()) }
    Ok(result)
}
#[cfg(test)]
mod tests {
    #[test]
    fn matches_successful_c_payload_and_keeps_relock_and_both_ss_operands() {
        let p=super::generate().unwrap();
        let word=|o|u32::from_le_bytes(p[o..o+4].try_into().unwrap());
        assert_eq!(word(0xf988),0x88888888);
        assert_eq!(word(0xf9a4),0x409664);
        assert_eq!(word(0xbb20),8);
        assert_eq!(word(0xbb38),0x40966c);
        assert_eq!(word(0xbb4c),0xffffff8f);
    }
}
